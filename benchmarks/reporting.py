from __future__ import annotations

import json
from typing import TYPE_CHECKING, Any

from benchmarks.cases import list_cases
from benchmarks.core import load_result
from benchmarks.inventory import ClaimRecord, load_claims

if TYPE_CHECKING:
    from collections.abc import Mapping
    from pathlib import Path


def _escape(value: Any) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def _format_value(value: int | float, unit: str) -> str:
    formatted = f"{value:,}" if isinstance(value, int) else f"{value:.6g}"
    return f"{formatted} {unit}"


def _statistic(metric: Mapping[str, Any]) -> str:
    statistic = str(metric.get("statistic", "derived"))
    method = metric.get("method")
    return f"{statistic}; {method}" if method else statistic


def _result_files(root: Path) -> list[Path]:
    result_dir = root / "benchmarks" / "results"
    return sorted(result_dir.glob("*.json")) if result_dir.is_dir() else []


def _claims(root: Path) -> tuple[ClaimRecord, ...]:
    path = root / "benchmarks" / "claims.toml"
    return load_claims(path) if path.is_file() else ()


def _artifact_link(root: Path, path: Path) -> str:
    relative = path.relative_to(root).as_posix()
    url = f"https://github.com/JetBrains-Research/opaque/blob/main/{relative}"
    return f"[{path.name}]({url})"


def _render_claims(claims: tuple[ClaimRecord, ...]) -> list[str]:
    lines = ["## Claim decisions", ""]
    if not claims:
        return [*lines, "No claims are registered.", ""]
    lines.extend(
        [
            "| Claim | Status | Evidence owner | Decision |",
            "|---|---|---|---|",
        ]
    )
    lines.extend(
        (
            f"| {_escape(claim.statement)} | `{claim.status}` | "
            f"`{claim.case or claim.classification}` | {_escape(claim.decision)} |"
        )
        for claim in claims
    )
    lines.append("")
    return lines


def _render_result(root: Path, path: Path, result: Mapping[str, Any]) -> list[str]:
    case = result["case"]
    provenance = result["provenance"]
    git = provenance["git"]
    hardware = provenance["hardware"]
    accelerator = hardware.get("accelerator")
    device = accelerator.get("name") if isinstance(accelerator, dict) else None
    device = device or hardware["cpu"]
    lines = [
        f"### `{case['id']}` — {path.name}",
        "",
        f"Source data: {_artifact_link(root, path)}",
        "",
        f"- Timestamp: `{provenance['timestamp_utc']}`",
        f"- Commit: `{git['commit']}` (`dirty={str(git['dirty']).lower()}`)",
        f"- Hardware: `{device}` (`{hardware['machine']}`)",
        f"- Command: `{' '.join(provenance['command'])}`",
        f"- Configuration: `{json.dumps(case['config'], sort_keys=True)}`",
        "",
        "| Measurement | Parameters | Metric | Value | Statistic |",
        "|---|---|---|---:|---|",
    ]
    lines.extend(
        (
            f"| `{_escape(row['name'])}` | `{_escape(parameters)}` | "
            f"`{_escape(metric_name)}` | "
            f"{_format_value(metric['value'], metric['unit'])} | "
            f"`{_statistic(metric)}` |"
        )
        for row in result["measurements"]
        for parameters in [json.dumps(row.get("parameters", {}), sort_keys=True)]
        for metric_name, metric in row["metrics"].items()
    )
    lines.append("")
    comparisons = result.get("comparisons", [])
    if comparisons:
        lines.extend(
            [
                "| Comparison | Baseline | Candidate | Metric | Value |",
                "|---|---|---|---|---:|",
            ]
        )
        lines.extend(
            (
                f"| `{_escape(comparison['name'])}` | "
                f"`{_escape(comparison['baseline'])}` | "
                f"`{_escape(comparison['candidate'])}` | "
                f"`{_escape(comparison['metric'])}` | "
                f"{_format_value(comparison['value'], comparison['unit'])} |"
            )
            for comparison in comparisons
        )
        lines.append("")
    lines.extend(f"- Note: {_escape(note)}" for note in result.get("notes", []))
    if result.get("notes"):
        lines.append("")
    return lines


def render_repository(root: Path) -> str:
    artifacts = [(path, load_result(path)) for path in _result_files(root)]
    artifacts_by_case: dict[str, list[Path]] = {}
    for path, result in artifacts:
        artifacts_by_case.setdefault(result["case"]["id"], []).append(path)
    lines = [
        "# Reproducible benchmark evidence",
        "",
        "This page is generated by `python -m benchmarks render`. Do not edit it "
        "by hand. Exact values below come only from linked JSON artifacts; absent "
        "hardware results remain unpublished.",
        "",
        "## Case registry",
        "",
        "| Case | Devices | Presets | Committed results |",
        "|---|---|---|---|",
    ]
    for case in list_cases():
        links = ", ".join(
            _artifact_link(root, path)
            for path in artifacts_by_case.get(case.case_id, [])
        )
        lines.append(
            f"| `{case.case_id}` | `{', '.join(case.devices)}` | "
            f"`{', '.join(case.presets)}` | {links or '—'} |"
        )
    lines.append("")
    lines.extend(_render_claims(_claims(root)))
    lines.extend(["## Recorded measurements", ""])
    if not artifacts:
        lines.extend(["No benchmark results are committed.", ""])
    else:
        for path, result in artifacts:
            lines.extend(_render_result(root, path, result))
    return "\n".join(lines).rstrip() + "\n"


__all__ = ["render_repository"]
